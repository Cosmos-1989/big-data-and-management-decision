def replace(chapter, title, index, old, new):
    slide = next(s for s in DECKS[chapter]['slides'] if s['title'] == title)
    assert old in slide['body'][index], (chapter, title, old)
    slide['body'][index] = slide['body'][index].replace(old, new)
    EDITS.append({'chapter': chapter, 'slide': title, 'before': old, 'after': new})


def prepare(chapter, before, title, lead, body, items, terms):
    ref = copy.deepcopy(next(s for s in DECKS[chapter]['slides'] if s['title'] == before)['detailRef'])
    page = dict(kind='concept', section='概念与比较依据', title=title, lead=lead,
                body=body, visual={'kind': 'cards', 'items': items},
                takeaway=body[-1].split('。')[-2] + '。', layout='split', density='compact', detailRef=ref)
    INSERTS[chapter].setdefault(before, []).append(page)
    for term, aliases, explanation in terms:
        TERMS.append(dict(chapter=chapter, lesson=int(chapter[:2]), term=term,
                          aliases=aliases, firstSlideTitle=title,
                          definitionSlideTitle=title, explanation=explanation))


def same_page(chapter, term, aliases, title, explanation):
    TERMS.append(dict(chapter=chapter, lesson=int(chapter[:2]), term=term,
                      aliases=aliases, firstSlideTitle=title,
                      definitionSlideTitle=title, explanation=explanation))


